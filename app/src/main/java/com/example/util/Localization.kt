object Localization {
    fun formatCurrency(amount: Double, language: AppLanguage): String {
        val formattedNumber = String.format(java.util.Locale.US, "%,.2f", amount)
        val numString = if (language == AppLanguage.BN) {
            toBanglaDigits(formattedNumber)
        } else {
            formattedNumber
        }
        return "৳ $numString"
    }

    fun formatNumber(number: Int, language: AppLanguage): String {
        return if (language == AppLanguage.BN) {
            toBanglaDigits(number.toString())
        } else {
            number.toString()
        }
    }

    fun toBanglaDigits(input: String): String {
        val banglaDigits = mapOf(
            '0' to '০', '1' to '১', '2' to '২', '3' to '৩', '4' to '৪',
            '5' to '৫', '6' to '৬', '7' to '৭', '8' to '৮', '9' to '৯'
        )
        val sb = StringBuilder()
        for (ch in input) {
            sb.append(banglaDigits[ch] ?: ch)
        }
        return sb.toString()
    }

